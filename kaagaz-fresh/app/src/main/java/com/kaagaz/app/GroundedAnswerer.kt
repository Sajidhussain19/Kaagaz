package com.kaagaz.app

import java.util.Locale

enum class AnswerSource(val label: String) {
    GEMMA("Gemma · on-device · grounded"),
    POLICY_ENGINE("Policy engine · deterministic"),
    FACT_LEDGER("Trust Ledger · deterministic"),
    EXTRACTIVE("Best matching passage · no LLM"),
    CONFLICT("Conflicting sources"),
    ABSTAIN("Not found")
}

data class GroundedAnswer(
    val question: String,
    val text: String,
    val source: AnswerSource,
    val evidence: List<EvidenceRef>,
    val followUps: List<String> = emptyList(),
    val note: String? = null,
    val retrieved: List<ScoredChunk> = emptyList()
)

/**
 * Retrieval-augmented, evidence-first answering. Order of authority:
 *  1. Person facts with conflicting sources are reported as a conflict, never answered with one value.
 *  2. Nothing relevant retrieved → abstain.
 *  3. Gemma (if verified on device) answers from numbered evidence only; its answer is rejected if it cites
 *     nothing, cites unknown passages, or contains a number that is not in the cited evidence.
 *  4. Otherwise the deterministic policy engine or the best passage, clearly labelled.
 */
class GroundedAnswerer(private val llm: LlmClient) {
    data class Corpus(val documents: List<AuditDocument>, val chunks: List<Chunk>, val facts: List<Fact>, val ledger: List<LedgerEntry>)

    fun answer(question: String, corpus: Corpus): GroundedAnswer {
        val q = question.trim()
        if (q.isBlank()) return GroundedAnswer(q, "Ask a question about your saved documents.", AnswerSource.ABSTAIN, emptyList())

        val factType = FieldIdentifier.identify(q)?.takeIf { it.scope == FactScope.PERSON && asksForFact(q) }
        if (factType != null) {
            val entry = corpus.ledger.firstOrNull { it.type == factType }
            when (entry?.state) {
                TrustState.CONFLICTING -> return GroundedAnswer(q,
                    "Your documents disagree: " + entry.groups.joinToString(" vs ") { "${it.display} (${it.documents.joinToString()})" } + ".",
                    AnswerSource.CONFLICT, entry.groups.flatMap { g -> g.facts.map { it.ref() } },
                    listOf("Resolve this in the Trust Ledger", "Run the Paperwork Crash Test"), "Kaagaz will not pick a value until you choose one.")
                TrustState.VERIFIED, TrustState.NEEDS_CONFIRMATION -> {
                    val g = entry.groups.first()
                    return GroundedAnswer(q, "${g.display}." + if (entry.state == TrustState.NEEDS_CONFIRMATION) " (needs your confirmation)" else "",
                        AnswerSource.FACT_LEDGER, g.facts.map { it.ref() }, followUps(factType), entry.reason)
                }
                else -> Unit
            }
        }

        val retriever = HybridRetriever(corpus.chunks, corpus.facts)
        val hits = retriever.search(q)
        if (hits.isEmpty()) return GroundedAnswer(q, "I couldn't find this in your saved documents.", AnswerSource.ABSTAIN, emptyList(),
            listOf("Scan the document that states it"), "No passage matched the question's key terms.")

        var rejection: String? = null
        if (llm.isReady) {
            when (val result = llm.generate(prompt(q, hits), SYSTEM, maxTokens = 120)) {
                is LlmResult.Text -> {
                    val verdict = validate(result.text, hits)
                    if (verdict.ok) {
                        val cited = verdict.cited.map { hits[it - 1] }
                        return if (verdict.notFound) GroundedAnswer(q, "The retrieved passages do not answer this.", AnswerSource.ABSTAIN, emptyList(),
                            note = "Gemma judged the evidence insufficient (${result.latencyMs} ms).", retrieved = hits)
                        else GroundedAnswer(q, verdict.clean, AnswerSource.GEMMA, cited.map { it.ref() }, followUpsFor(q),
                            "Generated by ${llm.label} in ${result.latencyMs} ms from ${hits.size} retrieved passages; numbers checked against evidence.", hits)
                    }
                    rejection = "Gemma's answer was rejected: ${verdict.reason}."
                }
                is LlmResult.Failed -> rejection = result.reason
                is LlmResult.Unavailable -> Unit
            }
        }

        val top = hits.first()
        val doc = corpus.documents.firstOrNull { it.id == top.chunk.documentId }
        // Document facts (due date, amount, premium, expiry) come from the top-ranked document's extracted fields.
        val docType = FieldIdentifier.identify(q)?.takeIf { it.scope == FactScope.DOCUMENT }
        if (docType != null) {
            val fact = corpus.facts.firstOrNull { it.documentId == top.chunk.documentId && it.type == docType }
                ?: hits.asSequence().mapNotNull { h -> corpus.facts.firstOrNull { it.documentId == h.chunk.documentId && it.type == docType } }.firstOrNull()
            if (fact != null) {
                val related = when (docType) {
                    FactType.DUE_DATE -> corpus.facts.firstOrNull { it.documentId == fact.documentId && it.type == FactType.BILL_AMOUNT }
                    FactType.BILL_AMOUNT -> corpus.facts.firstOrNull { it.documentId == fact.documentId && it.type == FactType.DUE_DATE }
                    else -> null
                }
                val same = corpus.facts.filter { it.type == docType && it.normalized == fact.normalized && it.documentId != fact.documentId }.map { it.documentName }.distinct()
                val text = "${docType.label}: ${Normalizer.display(docType, fact.normalized, fact.rawValue)}" +
                    (related?.let { " · ${it.type.label.lowercase(Locale.ENGLISH)} ${Normalizer.display(it.type, it.normalized, it.rawValue)}" } ?: "") + "."
                return GroundedAnswer(q, text, AnswerSource.FACT_LEDGER, listOfNotNull(fact.ref(), related?.ref()), followUpsFor(q),
                    listOfNotNull(rejection, "From ${fact.documentName}, page ${fact.page}.", same.takeIf { it.isNotEmpty() }?.let { "The same value also appears in ${it.joinToString()} — check for a duplicate." }).joinToString(" "), hits)
            }
        }
        if (doc != null && CoverageIntelligenceEngine.supports(q)) {
            val coverage = CoverageIntelligenceEngine.answer(q, doc.pages, doc.insuranceFields)
            if (coverage.kind == CoverageIntelligenceEngine.AnswerKind.RESULTS) return GroundedAnswer(q, coverage.summary, AnswerSource.POLICY_ENGINE,
                coverage.passages.take(3).map { p -> EvidenceRef(doc.id, doc.name, p.evidence.firstOrNull()?.pageNumber ?: 1, p.wording) },
                followUpsFor(q), listOfNotNull(rejection, "From ${doc.name}.").joinToString(" "), hits)
        }
        val sentence = bestSentence(top.chunk, top.matched, retriever)
        return GroundedAnswer(q, "“${sentence.take(220)}”", AnswerSource.EXTRACTIVE, listOf(top.ref()), followUpsFor(q),
            listOfNotNull(rejection, "Quoted from ${top.chunk.documentName}, page ${top.chunk.page}. No language model wrote this.").joinToString(" "), hits)
    }

    data class Verdict(val ok: Boolean, val clean: String, val cited: List<Int>, val notFound: Boolean, val reason: String)

    fun validate(raw: String, hits: List<ScoredChunk>): Verdict {
        val text = raw.trim().removePrefix("Answer:").trim()
        if (text.contains("NOT_FOUND", ignoreCase = true)) return Verdict(true, "", emptyList(), true, "")
        val cited = Regex("\\[(\\d+)]").findAll(text).map { it.groupValues[1].toInt() }.toList().distinct()
        if (cited.isEmpty()) return Verdict(false, text, cited, false, "it cited no evidence")
        if (cited.any { it !in 1..hits.size }) return Verdict(false, text, cited, false, "it cited a passage that does not exist")
        val evidenceDigits = cited.joinToString(" ") { hits[it - 1].chunk.text }.let(::numbers)
        val answerNumbers = numbers(text.replace(Regex("\\[\\d+]"), ""))
        val invented = answerNumbers.filter { it !in evidenceDigits }
        if (invented.isNotEmpty()) return Verdict(false, text, cited, false, "it stated ${invented.joinToString()} which is not in the cited evidence")
        val lines = text.lines().filter { it.isNotBlank() }
        val clean = lines.take(2).joinToString(" ").let { if (it.length > 260) it.take(257) + "…" else it }
        return Verdict(true, clean, cited, false, "")
    }

    /** Numbers as digit strings without separators ("₹1,50,000" → "150000", "8.40" → "8.4"). */
    fun numbers(text: String): Set<String> = Regex("\\d[\\d,]*(?:\\.\\d+)?").findAll(text).map { m ->
        m.value.replace(",", "").let { v -> if (v.contains('.')) v.trimEnd('0').trimEnd('.') else v }
    }.filter { it.isNotEmpty() }.toSet()

    fun prompt(question: String, hits: List<ScoredChunk>): String = buildString {
        appendLine("Evidence passages from the user's own documents:")
        hits.forEachIndexed { i, h -> appendLine("[${i + 1}] (${h.chunk.documentName}, page ${h.chunk.page}) ${h.chunk.text}") }
        appendLine()
        appendLine("Question: $question")
        append("Answer in at most two short sentences using only the passages, and cite them like [1]. Copy numbers exactly. If the passages do not answer the question, reply exactly NOT_FOUND.")
    }

    private fun asksForFact(q: String) = Regex("(?i)\\b(what|which|when|who|my|tell)\\b").containsMatchIn(q)

    /** The best sentence or OCR line: label-value schedules have no full stops, so lines are candidates too. */
    private fun bestSentence(chunk: Chunk, matched: Set<String>, retriever: HybridRetriever): String {
        val candidates = chunk.text.split(Regex("(?<=[.!?])\\s+")) + chunk.lines.map { it.text }
        return candidates.filter { it.isNotBlank() }
            .maxWithOrNull(compareBy<String> { s -> retriever.tokens(s).count { it in matched } }.thenBy { -it.length }) ?: chunk.text
    }

    private fun followUps(type: FactType) = listOf("Which documents mention my ${type.label.lowercase(Locale.ENGLISH)}?", "Run the Paperwork Crash Test")

    private fun followUpsFor(q: String): List<String> {
        val t = q.lowercase(Locale.ENGLISH)
        return when {
            "cover" in t -> listOf("What are the exclusions and waiting periods?", "What limits or sub-limits apply?")
            "bill" in t || "due" in t || "pay" in t -> listOf("Are there duplicate bills?", "What is the outstanding premium?")
            else -> listOf("What information is missing?", "Run the Paperwork Crash Test")
        }
    }

    private fun Fact.ref() = EvidenceRef(documentId, documentName, page, evidence)
    private fun ScoredChunk.ref() = EvidenceRef(chunk.documentId, chunk.documentName, chunk.page, chunk.text)

    companion object {
        const val SYSTEM = "You are Kaagaz, a careful assistant that answers questions about the user's personal documents. " +
            "Use only the evidence passages provided. Never guess, never add facts, never round numbers. Keep answers under 40 words."
    }
}
